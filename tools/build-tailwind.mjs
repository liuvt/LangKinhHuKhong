// Compile Tailwind CSS utilities used by Razor components, without a running JS dev server.
// Requires `npm install` in project root only when rebuilding CSS. The checked-in CSS works without Node.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'tailwindcss';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
function scan(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    const name = path.join(dir, e.name);
    if (e.isDirectory()) return scan(name);
    return name.endsWith('.razor') ? [name] : [];
  });
}
const candidates = new Set();
for (const f of scan(path.join(root, 'LangKinhHuKhong.Web', 'Components'))) {
  const html = fs.readFileSync(f, 'utf8');
  for (const match of html.matchAll(/\bclass="([^"\r\n]*)"/g)) {
    for (const token of match[1].split(/\s+/)) {
      if (/^[\w!:\[\]#.%/-]+$/.test(token)) candidates.add(token);
    }
  }
}
const input = fs.readFileSync(path.join(root, 'styles', 'tailwind.input.css'), 'utf8');
const defaultTheme = fs.readFileSync(path.join(root, 'node_modules', 'tailwindcss', 'theme.css'), 'utf8');
const { build } = await compile(defaultTheme + '\n' + input);
const preflight = fs.readFileSync(path.join(root, 'node_modules', 'tailwindcss', 'preflight.css'), 'utf8');
const result = `/* Generated by tools/build-tailwind.mjs. Do not edit manually. */\n${preflight}\n${build(Array.from(candidates))}\n`;
const out = path.join(root, 'LangKinhHuKhong.Web', 'wwwroot', 'css', 'tailwind.generated.css');
fs.writeFileSync(out, result);
console.log(`Generated ${path.relative(root, out)} — ${candidates.size} candidates, ${result.length} bytes.`);
